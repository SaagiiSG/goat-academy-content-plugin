#!/usr/bin/env node
// GOAT Content Machine autopilot: installs a daily OS job that starts Claude Code
// unattended and runs the goat-autopilot skill. No dependencies (Node 18+).
//
//   node autopilot.mjs install [--time 09:00]   create or update the daily job
//   node autopilot.mjs uninstall                 remove it
//   node autopilot.mjs status                    show whether it is installed + last log lines
//   node autopilot.mjs run                       run once now (same as the scheduled job)
//
// Files: ~/.goat-academy/autopilot/run.sh | run.cmd, autopilot.log
// macOS: ~/Library/LaunchAgents/com.goatacademy.autopilot.plist (runs missed jobs on wake)
// Linux: a crontab line tagged "# goat-autopilot"
// Windows: Task Scheduler task "GOAT Autopilot"
import { execSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const HOME = os.homedir();
const DIR = path.join(HOME, ".goat-academy", "autopilot");
const LOG = path.join(DIR, "autopilot.log");
const KEYS = path.join(HOME, ".goat-academy", "keys.env");
const LABEL = "com.goatacademy.autopilot";
const PLIST = path.join(HOME, "Library", "LaunchAgents", `${LABEL}.plist`);
const TASK = "GOAT Autopilot";
const isWin = process.platform === "win32", isMac = process.platform === "darwin";

const PROMPT = "Run the goat-content-machine:goat-autopilot skill now. This is an unattended scheduled run: nobody is at the computer, so never wait for an answer.";
const TOOLS = [
  "Skill", "Read", "Write", "Edit", "Glob", "Grep", "Bash",
  "mcp__plugin_goat-content-machine_goat-browser__*",
];

function which(bin) {
  try {
    const out = execSync(isWin ? `where ${bin}` : `command -v ${bin}`, { stdio: ["ignore", "pipe", "ignore"], shell: isWin ? undefined : "/bin/sh" }).toString().trim().split(/\r?\n/)[0];
    return out || null;
  } catch { return null; }
}

function parseTime(argv) {
  const i = argv.indexOf("--time");
  const t = i >= 0 ? argv[i + 1] : "09:00";
  const m = /^(\d{1,2}):(\d{2})$/.exec(t || "");
  if (!m || +m[1] > 23 || +m[2] > 59) throw new Error(`--time must look like 09:00 (got ${t})`);
  return { h: +m[1], m: +m[2], text: `${m[1].padStart(2, "0")}:${m[2]}` };
}

function writeRunner(claude) {
  fs.mkdirSync(DIR, { recursive: true });
  const toolArgs = TOOLS.map(t => `"${t}"`).join(" ");
  if (isWin) {
    const f = path.join(DIR, "run.cmd");
    const lines = [
      "@echo off",
      `cd /d "%USERPROFILE%\\.goat-academy"`,
      `rem keys come from the user environment (see goat-setup)`,
      `echo ==== %DATE% %TIME% >> "${LOG}"`,
      `"${claude}" -p "${PROMPT}" --permission-mode acceptEdits --allowedTools ${toolArgs} >> "${LOG}" 2>&1`,
    ];
    fs.writeFileSync(f, lines.join("\r\n") + "\r\n");
    return f;
  }
  const f = path.join(DIR, "run.sh");
  const pathDirs = [path.dirname(claude), path.dirname(process.execPath), "/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin"];
  const sh = `#!/bin/sh
# GOAT autopilot runner (generated by autopilot.mjs). Edit with: node autopilot.mjs install
export PATH="${[...new Set(pathDirs)].join(":")}:$PATH"
[ -f "${KEYS}" ] && set -a && . "${KEYS}" && set +a
cd "${path.join(HOME, ".goat-academy")}" || exit 1
# one run at a time
LOCK="${path.join(DIR, "run.lock")}"
if [ -f "$LOCK" ] && [ $(( $(date +%s) - $(cat "$LOCK" 2>/dev/null || echo 0) )) -lt 10800 ]; then echo "$(date) already running, skip" >> "${LOG}"; exit 0; fi
date +%s > "$LOCK"; trap 'rm -f "$LOCK"' EXIT
echo "==== $(date)" >> "${LOG}"
"${claude}" -p "${PROMPT}" --permission-mode acceptEdits --allowedTools ${toolArgs} >> "${LOG}" 2>&1
`;
  fs.writeFileSync(f, sh, { mode: 0o755 });
  return f;
}

function install(argv) {
  const claude = which("claude");
  if (!claude) throw new Error("claude command not found in PATH. Install Claude Code first.");
  const t = parseTime(argv);
  const runner = writeRunner(claude);
  if (isMac) {
    const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>${LABEL}</string>
  <key>ProgramArguments</key><array><string>/bin/sh</string><string>${runner}</string></array>
  <key>StartCalendarInterval</key><dict><key>Hour</key><integer>${t.h}</integer><key>Minute</key><integer>${t.m}</integer></dict>
  <key>StandardOutPath</key><string>${LOG}</string>
  <key>StandardErrorPath</key><string>${LOG}</string>
</dict></plist>
`;
    fs.mkdirSync(path.dirname(PLIST), { recursive: true });
    spawnSync("launchctl", ["unload", PLIST], { stdio: "ignore" });
    fs.writeFileSync(PLIST, plist);
    const r = spawnSync("launchctl", ["load", PLIST], { encoding: "utf8" });
    if (r.status !== 0) throw new Error("launchctl load failed: " + (r.stderr || r.stdout));
  } else if (isWin) {
    const r = spawnSync("schtasks", ["/Create", "/F", "/SC", "DAILY", "/TN", TASK, "/TR", `"${runner}"`, "/ST", t.text], { encoding: "utf8" });
    if (r.status !== 0) throw new Error("schtasks failed: " + (r.stderr || r.stdout));
  } else {
    const cur = spawnSync("crontab", ["-l"], { encoding: "utf8" }).stdout || "";
    const kept = cur.split("\n").filter(l => l && !l.includes("# goat-autopilot"));
    kept.push(`${t.m} ${t.h} * * * /bin/sh "${runner}" # goat-autopilot`);
    const r = spawnSync("crontab", ["-"], { input: kept.join("\n") + "\n", encoding: "utf8" });
    if (r.status !== 0) throw new Error("crontab failed: " + r.stderr);
  }
  console.log(`installed: daily at ${t.text} (${isMac ? "launchd" : isWin ? "Task Scheduler" : "cron"})`);
  console.log(`runner: ${runner}`);
  console.log(`log: ${LOG}`);
}

function uninstall() {
  if (isMac) { spawnSync("launchctl", ["unload", PLIST], { stdio: "ignore" }); fs.rmSync(PLIST, { force: true }); }
  else if (isWin) spawnSync("schtasks", ["/Delete", "/F", "/TN", TASK], { stdio: "ignore" });
  else {
    const cur = spawnSync("crontab", ["-l"], { encoding: "utf8" }).stdout || "";
    spawnSync("crontab", ["-"], { input: cur.split("\n").filter(l => l && !l.includes("# goat-autopilot")).join("\n") + "\n" });
  }
  console.log("uninstalled: the daily job is removed (files in ~/.goat-academy are kept)");
}

function status() {
  let installed = false;
  if (isMac) installed = fs.existsSync(PLIST);
  else if (isWin) installed = spawnSync("schtasks", ["/Query", "/TN", TASK], { stdio: "ignore" }).status === 0;
  else installed = (spawnSync("crontab", ["-l"], { encoding: "utf8" }).stdout || "").includes("# goat-autopilot");
  console.log(installed ? "status: installed" : "status: not installed");
  if (fs.existsSync(LOG)) {
    const lines = fs.readFileSync(LOG, "utf8").trim().split("\n");
    console.log("last log lines:\n" + lines.slice(-15).join("\n"));
  }
}

function runNow() {
  const runner = path.join(DIR, isWin ? "run.cmd" : "run.sh");
  if (!fs.existsSync(runner)) throw new Error("not installed yet: run `node autopilot.mjs install` first");
  const r = isWin ? spawnSync("cmd", ["/c", runner], { stdio: "inherit" }) : spawnSync("/bin/sh", [runner], { stdio: "inherit" });
  process.exit(r.status ?? 0);
}

const [cmd, ...rest] = process.argv.slice(2);
try {
  if (cmd === "install") install(rest);
  else if (cmd === "uninstall") uninstall();
  else if (cmd === "status") status();
  else if (cmd === "run") runNow();
  else { console.log("usage: node autopilot.mjs install [--time 09:00] | uninstall | status | run"); process.exit(1); }
} catch (e) { console.error("error: " + e.message); process.exit(1); }
